export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, th };

/** Looks up a message and fills in {placeholders}. Falls back to English, then to the key. */
export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = MESSAGES[locale][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "th" || value === "en";
}
